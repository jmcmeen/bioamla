"""
Coordinate redaction for publishing datasets.

Recorder metadata puts each file's exact ``latitude``/``longitude`` in a
dataset's ``metadata.csv``, catalog downloads add a ``location`` (a place name,
or ``"lat,lon"`` for iNaturalist), and the manifest summarizes coordinates as
``sites``. For sensitive species or private land those shouldn't be published
as-is. The functions here build redacted copies of a dataset's files for upload,
leaving the local dataset untouched:

- ``round``: coordinate columns are rounded to a number of decimal places (2 is
  about 1 km, 1 about 11 km, 0 about 111 km).
- ``strip``: coordinate columns are dropped and the manifest lists no sites.

Either way, free-text location columns are dropped, since text can't be rounded.

Not covered (:func:`unredacted_location_files` reports these so callers can
warn): GPS embedded in audio files (GUANO and other recorder chunks), JSON/JSONL
and text files that mention coordinates, and Parquet files.
"""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path
from typing import Any

from bioamla.exceptions import DatasetError, InvalidInputError

COORDINATE_MODES = ("keep", "round", "strip")
# Header names (compared case-insensitively) holding a latitude or longitude.
LATITUDE_COLUMNS = ("latitude", "lat")
LONGITUDE_COLUMNS = ("longitude", "lon", "lng", "long")
# Free-text location columns: a place name, or "lat,lon" (iNaturalist).
LOCATION_TEXT_COLUMNS = ("location", "locality")
_TABLE_DELIMITERS = {".csv": ",", ".tsv": "\t"}
_CARD_MARKER = "_Generated by bioamla._"
_SITES_LINE = "- **Sites:**"


def check_coordinate_mode(mode: str, decimals: int) -> None:
    """
    Validate a coordinate mode and rounding precision.

    Raises:
        InvalidInputError: For an unknown mode or ``decimals`` outside 0-6.
    """
    if mode not in COORDINATE_MODES:
        raise InvalidInputError(
            f"Unknown coordinate mode {mode!r}; use one of {', '.join(COORDINATE_MODES)}"
        )
    if not 0 <= decimals <= 6:
        raise InvalidInputError(f"coordinate decimals must be between 0 and 6, got {decimals}")


def _kind(column: str) -> str | None:
    """``"coordinate"``, ``"text"`` or None for a header name."""
    name = column.strip().lower()
    if name in LATITUDE_COLUMNS or name in LONGITUDE_COLUMNS:
        return "coordinate"
    if name in LOCATION_TEXT_COLUMNS:
        return "text"
    return None


def location_columns(fieldnames: list[str]) -> list[str]:
    """The headers in ``fieldnames`` that carry a location (coordinates or place text)."""
    return [f for f in fieldnames if _kind(f) is not None]


def redact_rows(
    rows: list[dict[str, Any]], fieldnames: list[str], mode: str, decimals: int = 2
) -> tuple[list[dict[str, Any]], list[str]]:
    """
    Round or strip the location columns of metadata rows.

    Args:
        rows: Metadata rows (not modified).
        fieldnames: Their column order.
        mode: ``keep``, ``round`` or ``strip``.
        decimals: Decimal places kept by ``round``.

    Returns:
        ``(rows, fieldnames)``: copies with coordinate columns rounded (values
        that aren't numbers are blanked) or dropped. Free-text location columns
        are dropped in both modes.

    Raises:
        InvalidInputError: For an unknown mode or bad ``decimals``.
    """
    check_coordinate_mode(mode, decimals)
    if mode == "keep":
        return [dict(r) for r in rows], list(fieldnames)

    drop = {f for f in fieldnames if _kind(f) == "text"}
    if mode == "strip":
        drop |= {f for f in fieldnames if _kind(f) == "coordinate"}
    rounded = [f for f in fieldnames if f not in drop and _kind(f) == "coordinate"]

    redacted = []
    for row in rows:
        new = {k: v for k, v in row.items() if k not in drop}
        for column in rounded:
            value = new.get(column)
            if value in (None, ""):
                continue
            try:
                new[column] = f"{round(float(value), decimals):.{decimals}f}"
            except (TypeError, ValueError):
                new[column] = ""  # never publish a value we couldn't round
        redacted.append(new)
    return redacted, [f for f in fieldnames if f not in drop]


def redact_sites(sites: list[dict[str, Any]], mode: str, decimals: int = 2) -> list[dict[str, Any]]:
    """
    Round or drop a manifest's ``sites``, merging sites that round together.

    Raises:
        InvalidInputError: For an unknown mode or bad ``decimals``.
    """
    check_coordinate_mode(mode, decimals)
    if mode == "keep":
        return [dict(s) for s in sites]
    if mode == "strip":
        return []
    merged: dict[tuple[float, float], int] = {}
    for site in sites:
        try:
            key = (
                round(float(site["latitude"]), decimals),
                round(float(site["longitude"]), decimals),
            )
        except (KeyError, TypeError, ValueError):
            continue
        merged[key] = merged.get(key, 0) + int(site.get("files") or 0)
    return [
        {"latitude": lat, "longitude": lon, "files": n} for (lat, lon), n in sorted(merged.items())
    ]


def _tables(base: Path) -> list[Path]:
    return sorted(p for p in base.rglob("*") if p.suffix.lower() in _TABLE_DELIMITERS)


def _read_table(path: Path) -> tuple[list[str], list[dict[str, Any]]]:
    """Read a CSV/TSV. Raises DatasetError if it can't be read cleanly."""
    try:
        with path.open(newline="", encoding="utf-8-sig") as f:
            reader = csv.DictReader(f, delimiter=_TABLE_DELIMITERS[path.suffix.lower()])
            fieldnames = list(reader.fieldnames or [])
            rows = list(reader)
    except (OSError, UnicodeDecodeError, csv.Error) as e:
        raise DatasetError(f"Can't read {path.name} to redact it: {e}") from e
    if any(None in row for row in rows):
        raise DatasetError(f"Can't redact {path.name}: a row has more fields than the header")
    return fieldnames, rows


def has_location_columns(dataset_dir: str | Path) -> bool:
    """
    Whether any CSV/TSV in the dataset has a location column with a value.

    Files that can't be read are skipped (this only decides whether to warn).
    """
    for path in _tables(Path(dataset_dir)):
        try:
            fieldnames, rows = _read_table(path)
        except DatasetError:
            continue
        columns = location_columns(fieldnames)
        if columns and any(row.get(c) for row in rows for c in columns):
            return True
    return False


def redacted_dataset_files(
    dataset_dir: str | Path, mode: str, decimals: int = 2
) -> dict[str, bytes]:
    """
    Build redacted copies of a dataset's files that carry locations.

    Covers every CSV/TSV with a location column, the ``dataset.json``
    manifest's ``sites``, and a ``README.md`` that bioamla generated (rebuilt
    from the redacted manifest, or with its Sites line removed when there is
    nothing to rebuild it from). A hand-written README is left alone.

    Args:
        dataset_dir: Dataset directory.
        mode: ``keep``, ``round`` or ``strip``.
        decimals: Decimal places kept by ``round``.

    Returns:
        Mapping of path (relative to ``dataset_dir``, POSIX style) to the
        redacted file content. Empty for ``keep``, or when nothing carries a
        location.

    Raises:
        InvalidInputError: For an unknown mode or bad ``decimals``.
        DatasetError: If a file that may carry locations can't be read or
            parsed (it is never uploaded unredacted).
    """
    from bioamla.datasets.manifest import (
        DatasetManifest,
        build_dataset_card,
        build_manifest_from_metadata,
    )

    check_coordinate_mode(mode, decimals)
    if mode == "keep":
        return {}

    base = Path(dataset_dir)
    out: dict[str, bytes] = {}

    for path in _tables(base):
        fieldnames, rows = _read_table(path)
        if not location_columns(fieldnames):
            continue
        rows, fieldnames = redact_rows(rows, fieldnames, mode, decimals)
        buffer = io.StringIO()
        writer = csv.DictWriter(
            buffer,
            fieldnames=fieldnames,
            delimiter=_TABLE_DELIMITERS[path.suffix.lower()],
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)
        out[path.relative_to(base).as_posix()] = buffer.getvalue().encode("utf-8")

    manifest: DatasetManifest | None = None
    manifest_path = base / "dataset.json"
    if manifest_path.exists():
        try:
            data = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:
            raise DatasetError(f"Can't read dataset.json to redact it: {e}") from e
        if data.get("sites"):
            data["sites"] = redact_sites(data["sites"], mode, decimals)
            out["dataset.json"] = (json.dumps(data, indent=2, default=str) + "\n").encode("utf-8")
        manifest = DatasetManifest.from_dict(data)
    elif (base / "metadata.csv").exists():
        manifest = build_manifest_from_metadata(str(base))
        manifest.sites = redact_sites(manifest.sites, mode, decimals)

    readme = base / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8", errors="replace")
        if _CARD_MARKER in text:
            if manifest is not None:
                card = build_dataset_card(
                    manifest, published_decimals=decimals if mode == "round" else None
                )
            else:
                card = "".join(
                    line
                    for line in text.splitlines(keepends=True)
                    if not line.startswith(_SITES_LINE)
                )
            out["README.md"] = card.encode("utf-8")

    return out


def unredacted_location_files(dataset_dir: str | Path, wav_limit: int = 200) -> list[str]:
    """
    List files that may carry locations ``redacted_dataset_files`` doesn't change.

    - WAVs whose recorder metadata has a position (headers only; at most
      ``wav_limit`` WAVs are checked, since one is enough to know).
    - JSON/JSONL/TXT files (other than ``dataset.json``) that mention a
      latitude or longitude.
    - Parquet files, which aren't inspected.

    Returns:
        Paths relative to ``dataset_dir``.
    """
    from bioamla.audio.metadata import get_recording_metadata
    from bioamla.exceptions import BioamlaError

    base = Path(dataset_dir)
    found: list[str] = []
    wavs_checked = 0
    for path in sorted(base.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(base).as_posix()
        suffix = path.suffix.lower()
        if suffix == ".wav":
            if wavs_checked >= wav_limit:
                continue
            wavs_checked += 1
            try:
                meta = get_recording_metadata(str(path))
            except BioamlaError:
                continue
            if meta.latitude is not None or meta.longitude is not None:
                found.append(rel)
        elif suffix in (".json", ".jsonl", ".txt") and rel != "dataset.json":
            try:
                text = path.read_text(encoding="utf-8", errors="replace").lower()
            except OSError:
                continue
            if "latitude" in text or "longitude" in text:
                found.append(rel)
        elif suffix == ".parquet":
            found.append(rel)
    return found


